def plot_logs(log_dir: str, output_file: str):
    """
    Reads TensorBoard logs generated by Stable-Baselines3 and plots the key metrics.
    """
    log_path = Path(log_dir)
    if not log_path.exists():
        print(f"\n[Error] Log directory not found: {log_dir}")
        print("Make sure you have run the training script and generated logs.")
        return

    # Find the latest PPO run directory
    # SB3 creates folders like "PPO_1", "PPO_2", etc.
    run_dirs = [d for d in log_path.iterdir() if d.is_dir()]
    if not run_dirs:
        # Check if the log_dir itself contains the tfevents file
        run_dirs = [log_path]
    else:
        # Sort by creation time / name to get the latest
        run_dirs.sort(key=lambda x: x.stat().st_mtime)
        
    latest_run_dir = run_dirs[-1]
    
    # Find the tfevents file inside the run directory
    event_files = list(latest_run_dir.glob("*tfevents*"))
    
    if not event_files:
        print(f"\n[Error] No tensorboard event files found in {latest_run_dir}")
        return

    latest_event_file = event_files[0]
    print(f"[info] Reading metrics from latest run: {latest_run_dir.name}")

    # Load TensorBoard data
    # Size_guidance limits how many points are kept in memory (0 = keep all)
    ea = EventAccumulator(str(latest_event_file), size_guidance={'scalars': 0})
    ea.Reload()

    # Get available scalar tags
    available_tags = ea.Tags()['scalars']
    
    if not available_tags:
        print("[Error] No scalar metrics found in the log file.")
        return

    # Metrics we are most interested in observing for PPO
    target_metrics = [
        "rollout/ep_rew_mean",        # Average reward (Should go up)
        "rollout/ep_len_mean",        # Average episode length
        "train/policy_gradient_loss", # Policy network loss (Usually goes down/negative)
        "train/value_loss",           # Value network loss (Should go down)
        "train/entropy_loss",         # Entropy (Exploration - should slowly decrease)
        "train/learning_rate"         # LR schedule check
    ]
    
    # Filter only metrics that actually exist in this log file
    found_metrics = [m for m in target_metrics if m in available_tags]
    
    if not found_metrics:
        print(f"Could not find exact target metrics. Found tags instead: {available_tags}")
        # fallback to plot whatever is available
        found_metrics = available_tags[:6] 

    # Create subplots
    n_metrics = len(found_metrics)
    fig, axes = plt.subplots(n_metrics, 1, figsize=(12, 4 * n_metrics))
    if n_metrics == 1:
        axes = [axes]
        
    for ax, tag in zip(axes, found_metrics):
        # Extract events correctly
        events = ea.Scalars(tag)
        steps = [e.step for e in events]
        vals = [e.value for e in events]
        
        # Plot
        ax.plot(steps, vals, label=tag, color='#1f77b4', linewidth=2)
        ax.set_title(tag.upper().replace("/", " — "), fontweight='bold')
        ax.set_xlabel("Timesteps")
        
        # Add a moving average to smooth noisy graphs like loss
        if len(vals) > 5:
            import pandas as pd
            ma = pd.Series(vals).rolling(window=max(2, len(vals)//20)).mean()
            ax.plot(steps, ma, color='red', linestyle='--', alpha=0.8, label="Moving Avg")
            
        ax.grid(True, linestyle="--", alpha=0.6)
        ax.legend()
        
    plt.tight_layout()
    
    # Ensure output directory exists before saving
    Path(output_file).parent.mkdir(parents=True, exist_ok=True)
    plt.savefig(output_file, dpi=150)
    print(f"\n[success] Saved training performance graphs to: {output_file}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Read and plot PPO TensorBoard logs.")
    parser.add_argument("--log_dir", type=str, default="ppo_logs_spa", 
                        help="Path to the TensorBoard log directory")
    parser.add_argument("--output", type=str, default="data/eval/reports/training_metrics.png", 
                        help="Path to save the generated PNG image")
    
    args = parser.parse_args()
    plot_logs(args.log_dir, args.output)
